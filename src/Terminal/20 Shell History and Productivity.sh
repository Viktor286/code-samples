history # List previously run commands
!123 # Re-run the command at history line 123
!! # Re-run the last command
!ssh # Re-run the most recent command starting with "ssh"
Ctrl+R # Reverse-search command history interactively
Ctrl+A # Move cursor to the beginning of the line
Ctrl+E # Move cursor to the end of the line
Ctrl+L # Clear the terminal screen
clear # Clear the terminal screen
man ls # Open the manual page for a command
ls --help # Print a command's usage summary
watch -n 2 "df -h" # Re-run a command every 2 seconds
xargs --help | less # Combine a command with a pager
!$ # Reuse the last argument of the previous command
